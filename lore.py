def main() -> int:
    hook = (os.environ.get("DISCORD_WEBHOOK_NEWS") or os.environ.get("DISCORD_WEBHOOK_GUIDES") or "").strip()
    now = datetime.now(timezone.utc)
    title, text, icon = FACTS[now.date().toordinal() % len(FACTS)]
    embed = {
        "author": AUTHOR,
        "title": f"📚 Знаете ли вы? {title}",
        "description": text,
        "color": 0x69CCF0,
        "thumbnail": {"url": ICON.format(icon)},
        "footer": {"text": "Факт дня из библиотеки Даларана · WoW Forever", "icon_url": ICON.format("inv_misc_book_09")},
        "timestamp": now.isoformat(),
    }
    print("fact:", title)
    if hook:
        _send(hook, {**BOT, "embeds": [embed], "allowed_mentions": {"parse": []}, "flags": 4096})
    return 0


if __name__ == "__main__":
    sys.exit(main())

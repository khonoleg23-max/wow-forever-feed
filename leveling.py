def bracket(level: int):
    for b in BRACKETS:
        if b[0] <= level <= b[1]:
            return b
    return BRACKETS[-1] if level > 60 else BRACKETS[0]


def embed_for(b, level=None) -> dict:
    lo, hi, title, icon, zones, dungeons, tips = b
    rng = "60" if lo == hi else f"{lo}–{hi}"
    head = f"🧭 {level} уровень — {title}" if level else f"🧭 {rng}: {title}"
    return {
        "author": AUTHOR,
        "title": head,
        "color": COLOR,
        "thumbnail": {"url": ICON.format(icon)},
        "fields": [
            {"name": "🗺 Куда идти", "value": zones},
            {"name": "🏰 Подземелья", "value": dungeons},
            {"name": "💡 Совет Кадгара", "value": tips},
        ],
        "footer": {"text": f"Уровни {rng} · Альянс · WoW Forever · ✨ — новое в Forever"},
    }


def post() -> int:
    from discord_full import _send
    hook = os.environ.get("DISCORD_WEBHOOK_GUIDES", "").strip()
    intro = {
        "author": AUTHOR,
        "title": "📜 Путь героя Альянса: прокачка 1–60 в WoW Forever",
        "description": "Юные искатели приключений! Я собрал маршрут по землям Азерота — от первых шагов до вершины Хиджала. "
                       "Сверяйтесь с ним, а если заплутаете — спросите меня.\n\n" + HOWTO,
        "color": COLOR,
        "thumbnail": {"url": ICON.format("inv_misc_book_11")},
    }
    embeds = [intro] + [embed_for(b) for b in BRACKETS]
    for i in range(0, len(embeds), 4):  # ≤6000 символов на сообщение
        payload = {**BOT, "embeds": embeds[i:i + 4], "allowed_mentions": {"parse": []}, "flags": 4096}
        if hook:
            _send(hook, payload)
        print("sent", len(payload["embeds"]), "embeds")
    return 0


def _go(s: str) -> str:
    """Строка для шаблона Go (YAGPDB)."""
    return "`" + s.replace("`", "'") + "`"


def yagpdb() -> int:
    """Шаблон для YAGPDB: триггер-регэксп ^!(ур|уровень|lvl|лвл)\\s*(\\d+)."""
    parts = [
        '{{$m := reFindAllSubmatches `(?i)^!(?:ур|уровень|lvl|лвл)\\s*(\\d{1,2})` .Message.Content}}',
        '{{if not $m}}{{sendMessage nil "Напиши уровень цифрами, например: `!ур 23`"}}{{else}}',
        '{{$l := toInt (index (index $m 0) 1)}}{{if lt $l 1}}{{$l = 1}}{{end}}{{if gt $l 60}}{{$l = 60}}{{end}}',
    ]
    first = True
    for lo, hi, title, icon, zones, dungeons, tips in BRACKETS:
        cond = f"{{{{if le $l {hi}}}}}" if first else f"{{{{else if le $l {hi}}}}}"
        first = False
        rng = "60" if lo == hi else f"{lo}–{hi}"
        parts.append(
            cond
            + f"{{{{$t := {_go(title)}}}}}{{{{$i := {_go(icon)}}}}}{{{{$r := {_go(rng)}}}}}"
            + f"{{{{$z := {_go(zones)}}}}}{{{{$d := {_go(dungeons)}}}}}{{{{$s := {_go(tips)}}}}}"
        )
    parts.append("{{end}}")
    parts.append(
        '{{sendMessage nil (complexMessage "reply" .Message.ID "embed" (cembed '
        '"author" (sdict "name" "Кадгар, хранитель знаний Кирин-Тора" "icon_url" "https://wow.zamimg.com/images/wow/icons/large/quest_khadgar.jpg") '
        '"title" (print "🧭 " $l " уровень — " $t) "color" 6933744 '
        '"thumbnail" (sdict "url" (print "https://wow.zamimg.com/images/wow/icons/large/" $i ".jpg")) '
        '"fields" (cslice (sdict "name" "🗺 Куда идти" "value" $z) (sdict "name" "🏰 Подземелья" "value" $d) (sdict "name" "💡 Совет Кадгара" "value" $s)) '
        '"footer" (sdict "text" (print "Уровни " $r " · Альянс · WoW Forever · ✨ — новое в Forever · полный маршрут в #📖-библиотека-даларана"))))}}'
    )
    parts.append("{{end}}")
    out = Path(__file__).parent / "yagpdb" / "kadgar_level.gotmpl"
    out.parent.mkdir(exist_ok=True)
    text = "\n".join(parts) + "\n"
    out.write_text(text, encoding="utf-8")
    print(out, len(text), "chars")
    return 0



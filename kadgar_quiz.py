        + '{{$zones = print "Здесь ты всё прошёл — пора дальше:\\n" $out}}{{end}}',
        '{{if not $zones}}{{$zones = "Ты прошёл все зоны своего уровня — бери подземелья и задания-наводки!"}}{{end}}',
        pick.replace("@DATA@", "$D").replace("@HI@", "$hi").replace("@LO@", "$lo").replace("@DONE@", "$dd") + '{{$dun := $out}}',

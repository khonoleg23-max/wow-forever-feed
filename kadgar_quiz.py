def _skills():
    """Ключевые умения тренера (помечены «+» в addon_src/notes) с уровнем из данных Wowhead."""
    import json
    src = Path(__file__).parent / "addon_src"
    dig = json.loads((src / "digest.json").read_text(encoding="utf-8"))
    out = {}
    for c in CLASSES:
        lvl = {a["id"]: (a["lvl"], a["ru"]) for a in dig[c]["abilities"]}
        out[c] = []
        for line in (src / "notes" / f"{c}.txt").read_text(encoding="utf-8").splitlines():
            if line.startswith("+"):
                i = int(line[1:].split("|")[0])
                if i in lvl:
                    out[c].append(lvl[i])
        out[c].sort()
    return out



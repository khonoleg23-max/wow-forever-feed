def final(cls: str) -> str:
    role, emoji, spec, slug = CLASSES[cls]
    talents = "§".join(f"{a}|{t}" for a, t in TALENTS[cls])
    skills = ";".join(f"{a}|{n}" for a, n in SKILLS[cls])
    pick = (
        '{{$out := ""}}{{$n := 0}}{{range split @DATA@ ";"}}{{$f := split . "|"}}{{$a := toInt (index $f 2)}}{{$b := toInt (index $f 3)}}'
        '{{if and (le $a @HI@) (ge $b @LO@) (not (in @DONE@ (index $f 0))) (lt $n 4)}}'
        '{{$out = print $out "• **" (index $f 1) "** (" $a "–" $b ") — " (index $f 4) "\\n"}}{{$n = add $n 1}}{{end}}{{end}}'
    )
    return "".join([
        '{{$p := split (reReplace `^.*?kq-z-` .CustomID "") "-"}}',
        '{{$lo := toInt (index $p 1)}}{{$hi := toInt (index $p 2)}}{{$dd := split (index $p 3) "."}}{{$zd := .Values}}',
        f'{{{{$Z := {raw(zdata())}}}}}{{{{$D := {raw(ddata())}}}}}',
        # зоны: сначала по уровню, иначе — следующие
        pick.replace("@DATA@", "$Z").replace("@HI@", "$hi").replace("@LO@", "$lo").replace("@DONE@", "$zd") + '{{$zones := $out}}',
        '{{if not $zones}}' + pick.replace("@DATA@", "$Z").replace("@HI@", "(add $hi 8)").replace("@LO@", "(add $hi 1)").replace("@DONE@", "$zd")
        + '{{$zones = print "Здесь ты всё прошёл — пора дальше:\\n" $out}}{{end}}',
        '{{if not $zones}}{{$zones = "Ты прошёл все зоны своего уровня — бери подземелья и задания-наводки!"}}{{end}}',
        pick.replace("@DATA@", "$D").replace("@HI@", "$hi").replace("@LO@", "$lo").replace("@DONE@", "$dd") + '{{$dun := $out}}',
        '{{if not $dun}}' + pick.replace("@DATA@", "$D").replace("@HI@", "(add $hi 6)").replace("@LO@", "(add $hi 1)").replace("@DONE@", "$dd")
        + '{{$dun = $out}}{{if $dun}}{{$dun = print "Скоро откроются:\\n" $dun}}{{end}}{{end}}',
        '{{if lt $hi 13}}{{$dun = "Первые подземелья — с 13 уровня (✨ Чертоги Танов под Стальгорном)."}}{{else if not $dun}}{{$dun = "Подходящие подземелья пройдены — отличная работа!"}}{{end}}',
        # таланты
        f'{{{{$tal := ""}}}}{{{{$next := ""}}}}{{{{range split {raw(talents)} "§"}}}}{{{{$f := split . "|"}}}}',
        '{{if le (toInt (index $f 0)) $hi}}{{$tal = index $f 1}}{{else if not $next}}{{$next = print "С " (index $f 0) " ур.: " (index $f 1)}}{{end}}{{end}}',
        '{{if lt $hi 10}}{{$tal = "Таланты откроются на 10 уровне."}}{{end}}{{if $next}}{{$tal = print $tal "\\n\\n**Дальше.** " $next}}{{end}}',
        # умения
        f'{{{{$have := cslice}}}}{{{{$soon := cslice}}}}{{{{range split {raw(skills)} ";"}}}}{{{{$f := split . "|"}}}}{{{{$a := toInt (index $f 0)}}}}',
        '{{if le $a $hi}}{{$have = $have.Append (index $f 1)}}{{else if le $a (add $hi 6)}}{{$soon = $soon.Append (print (index $f 1) " (" $a ")")}}{{end}}{{end}}',
        '{{$sk := print "**Должно быть выучено** (и новые ранги у тренера каждые 2 уровня): " (joinStr ", " $have.StringSlice)}}',
        '{{if $soon}}{{$sk = print $sk "\\n**Скоро:** " (joinStr ", " $soon.StringSlice)}}{{end}}',
        f'{{{{$sk = print $sk "\\n**Можно сэкономить:** " {raw(SKIP[cls])}}}}}',
        '{{sendResponse nil (complexMessage "ephemeral" true "embed" (cembed '
        f'"author" {AUTHOR} "color" {COLOR} '
        f'"title" (print "{emoji} {role}, " $lo "–" $hi " уровень — твой путь") '
        '"fields" (cslice '
        '(sdict "name" "🗺 Куда идти" "value" $zones) '
        '(sdict "name" "🏰 Подземелья" "value" $dun) '
        f'(sdict "name" "🌟 Таланты · {spec}" "value" $tal) '
        '(sdict "name" "📖 Тренер" "value" $sk)) '
        f'"description" "[Полный гайд по классу на Wowhead]({GUIDE.format(slug)}) · маршрут — в #📖-библиотека-даларана" '
        '"footer" (sdict "text" "✨ — новое в WoW Forever · по гайдам Wowhead")))}}'
    ])


def main() -> None:
    OUT.mkdir(exist_ok=True)
    files = {"01_trigger.gotmpl": trigger(), "02_steps.gotmpl": steps()}
    for c in CLASSES:
        files[f"10_final_{c}.gotmpl"] = final(c)
    for name, text in files.items():
        (OUT / name).write_text(text + "\n", encoding="utf-8")
        flag = "OK" if len(text) <= LIMIT else "TOO LONG"
        print(f"{name:24} {len(text):6} {flag}")


if __name__ == "__main__":
    main()
